/*
Table of Contents plugin for ContentBuilder / ContentBox

Builds a linked "jump to" list from the page's headings (h2/h3/h4). Clicking an
item smooth-scrolls to that heading and marks it active. The list is generated by
mount() from the surrounding content; the title above it is editable inline. In
the editor it rebuilds live when you add/remove or rename a heading.

Usage (embed this HTML into your content):

<div data-cb-type="table-of-contents" data-cb-levels="h2h3" data-cb-accent-color="#3b82f6" role="navigation" aria-label="Table of contents">
    <p class="toc-title">On this page</p>
    <ul class="toc-list"></ul>
</div>
*/

export default {
    name: 'table-of-contents',
    displayName: 'Table of Contents',
    version: '1.0.0',

    settings: {
        _groups: [
            { id: 'content', label: 'Content', fields: ['levels'] },
            { id: 'appearance', label: 'Appearance', fields: ['accentColor'] }
        ],
        levels: {
            type: 'select',
            label: 'Heading Levels',
            default: 'h2h3',
            options: [
                { value: 'h2', label: 'H2 only' },
                { value: 'h2h3', label: 'H2 + H3' },
                { value: 'h2h3h4', label: 'H2 + H3 + H4' }
            ],
            group: 'content'
        },
        accentColor: { type: 'color', label: 'Accent Color', default: '#3b82f6', group: 'appearance' }
    },

    mount: function (element, options) {
        const opts = {
            levels: options.levels || 'h2h3',
            accentColor: options.accentColor || '#3b82f6'
        };

        const list = element.querySelector('.toc-list');
        if (!list) return {};

        element.style.setProperty('--toc-accent', opts.accentColor);
        element.setAttribute('role', 'navigation');
        if (!element.getAttribute('aria-label')) element.setAttribute('aria-label', 'Table of contents');

        const doc = element.ownerDocument || document;
        const selector = { h2: 'h2', h2h3: 'h2, h3', h2h3h4: 'h2, h3, h4' }[opts.levels] || 'h2, h3';
        const scope = element.closest('.is-container') || doc.body;
        const slug = (text) => text.toLowerCase().trim()
            .replace(/[^\w\s-]/g, '').replace(/\s+/g, '-').replace(/-+/g, '-').slice(0, 60) || 'section';

        const scanHeadings = () => Array.from(scope.querySelectorAll(selector))
            .filter((h) => !h.closest('[data-cb-type="table-of-contents"]') && h.textContent.trim() !== '');

        let headings = [];
        let linkFor = new Map();
        let observer = null;
        let lastSig = '';

        const setActive = (a) => {
            list.querySelectorAll('.toc-link').forEach((l) => l.classList.toggle('is-active', l === a));
        };

        // (Re)build the list from the current headings. Assigns ids to headings
        // that lack one. Clicking a link scrolls to the heading AND marks it active
        // (so an inline TOC shows the chapter you last jumped to).
        const buildList = () => {
            if (observer) observer.disconnect();
            headings = scanHeadings();
            linkFor = new Map();
            list.innerHTML = '';
            const used = new Set();
            headings.forEach((h) => {
                let id = h.id;
                if (!id) {
                    const base = slug(h.textContent);
                    let s = base, i = 2;
                    while (used.has(s) || (doc.getElementById(s) && doc.getElementById(s) !== h)) { s = base + '-' + i++; }
                    id = s;
                    h.id = id;
                }
                used.add(id);
                const li = document.createElement('li');
                li.className = 'toc-item toc-' + h.tagName.toLowerCase();
                const a = document.createElement('a');
                a.className = 'toc-link';
                a.href = '#' + id;
                a.textContent = h.textContent.trim();
                a.addEventListener('click', (e) => {
                    e.preventDefault();
                    h.scrollIntoView({ behavior: 'smooth', block: 'start' });
                    setActive(a);
                    try { history.replaceState(null, '', '#' + id); } catch (err) { /* ignore */ }
                });
                li.appendChild(a);
                list.appendChild(li);
                linkFor.set(h, a);
            });
            lastSig = headings.map((h) => h.tagName + ':' + h.textContent.trim()).join('|');
            if (observer) observer.observe(scope, { childList: true, subtree: true, characterData: true });
        };

        buildList();

        // Live refresh while editing (editor only): rebuild when the heading set or
        // any heading's text changes. Cheap signature check avoids churn on unrelated
        // edits, and the observer is disconnected during its own rebuild (no loop).
        let debounce = null;
        const inEditor = !!(doc.body && doc.body.classList.contains('data-editor'));
        if (inEditor) {
            observer = new MutationObserver(() => {
                clearTimeout(debounce);
                debounce = setTimeout(() => {
                    const sig = scanHeadings().map((h) => h.tagName + ':' + h.textContent.trim()).join('|');
                    if (sig !== lastSig) buildList();
                }, 400);
            });
            observer.observe(scope, { childList: true, subtree: true, characterData: true });
        }

        return {
            destroy() {
                if (observer) observer.disconnect();
                clearTimeout(debounce);
            }
        };
    },

    unmount: function (element, instance) {
        if (instance && instance.destroy) instance.destroy();
    }
};
